# 1. Path and Local Model Configuration
BASE_DIR = os.path.dirname(os.path.abspath(__file__))
DATASET_PATH = "data/dataset_splits/train_set.jsonl"
# 💡 Ollama model tag for DeepSeek-R1-Distill-Qwen-7B
OLLAMA_MODEL = "deepseek-r1:7b" 


def clean_deepseek_reasoning_output(raw_content: str) -> str:
    """
    Cleans <think>...</think> tags generated by DeepSeek-R1 reasoning process
    and extracts standard JSON blocks or JSON object strings.
    """
    if not raw_content:
        return "{}"
    
    # 1. Remove <think>...</think> tags and all internal reasoning steps
    cleaned = re.sub(r'<think>.*?</think>', '', raw_content, flags=re.DOTALL).strip()
    
    # 2. Try extracting text inside ```json ... ``` code block
    json_block = re.search(r'```json\s*(.*?)\s*```', cleaned, re.DOTALL)
    if json_block:
        return json_block.group(1).strip()
    
    # 3. Fallback: extract the outermost { ... } JSON object
    json_obj = re.search(r'\{.*\}', cleaned, re.DOTALL)
    if json_obj:
        return json_obj.group(0).strip()
    
    return cleaned


class SCGProcessor:
    def __init__(self, model_name: str = OLLAMA_MODEL):
        self.model_name = model_name
        # Pure offline local retriever
        self.retriever = MultiSourceRetriever()

    def _call_ollama_json(self, system_prompt: str, user_prompt: str) -> dict:
        """
        Ollama local call wrapper optimized for 8GB VRAM and DeepSeek-R1.
        """
        try:
            # 8GB VRAM optimization parameters (Context window & Gen length)
            options = {
                "temperature": 0.1,
                "num_ctx": 4096,     # Memory protection: limit context window to 4096 tokens
                "num_predict": 1024, # Memory protection: limit max generation tokens
                "top_p": 0.95
            }
            response = ollama.chat(
                model=self.model_name,
                messages=[
                    {"role": "system", "content": system_prompt},
                    {"role": "user", "content": user_prompt},
                ],
                format="json",  # Force structured JSON format
                options=options
            )
            raw_content = response['message']['content']
            
            # Clean DeepSeek-R1 specific <think> chain-of-thought content
            cleaned_json_str = clean_deepseek_reasoning_output(raw_content)
            return json.loads(cleaned_json_str)
        except Exception as e:
            print(f"\n⚠️ Ollama local API parsing/call failed (Details: {e})")
            return {}

    def extract_full_context_with_llm(
        self, full_sentence: str, target_claim: str
    ) -> dict:
        """Phase 1.1: Extract Context Shell and Context Nature dynamically using local DeepSeek-R1."""
        system_prompt = "You are a precise linguistic context analysis assistant. You MUST strictly output standard JSON format without any extra text."
        
        prompt = f"""Analyze the given sentence to extract the full context shell and the core assertion.
【Full Sentence】: "{full_sentence}"
【Core Assertion Reference】: "{target_claim}"
【Task Requirements】:
1. **context_shell_text**: Extract the full context shell or introductory clause that embeds the assertion (e.g., "In Alice's dream", "In children's science picture books, it is often written that"). If the sentence has no explicit context shell, output "Objective Reality Context".
2. **context_nature**: Analyze the functional properties and factuality constraints of this context (e.g., "Educational Science Context (requires strict empirical accuracy)", "Fairy Tale / Dream Context (tolerates counterfactuals)", "Personal Opinion Quotation Context").
Strictly return JSON format:
{{
  "context_shell_text": "full context shell text...",
  "context_nature": "context properties and factuality constraint description..."
}}
"""
        result = self._call_ollama_json(system_prompt, prompt)
        
        if not result:
            return {
                "context_shell_text": "Objective Reality Context",
                "context_nature": "Standard Physical Reality",
            }
        return result

    def parse_dataset_item(self, item: dict) -> tuple:
        """Phase 1: Parse input format + LLM context extraction + Local dynamic retrieval."""
        full_sentence = item.get("full_sentence", "")
        target_claim = item.get("base_text", item.get("target_claim", ""))
        corrected_full_sentence = item.get("correction", item.get("corrected_full_sentence", full_sentence))
        
        # 1. Call DeepSeek-R1 to extract full context shell and nature
        llm_context_info = self.extract_full_context_with_llm(
            full_sentence, target_claim
        )
        full_context_shell = llm_context_info.get("context_shell_text", "")
        context_nature = llm_context_info.get("context_nature", "")

        # 2. Trigger local dynamic retrieval
        initial_check = {}
        cs_ev = self.retriever.retrieve_by_task("COMMON_SENSE_CHECK", query=target_claim)
        initial_check["cs_evidence"] = cs_ev[0] if cs_ev else "No relevant commonsense evidence found."

        ctx_query = f"{full_context_shell} {target_claim}"
        ctx_ev = self.retriever.retrieve_by_task("CONTEXT_CHECK", query=ctx_query)
        initial_check["ctx_evidence"] = ctx_ev[0] if ctx_ev else "No relevant context evidence found."

        clause_tuple = {
            "sub_sentence": full_sentence,
            "full_context_shell": full_context_shell,
            "context_nature": context_nature,
            "pure_assertion": target_claim,
            "nest_level": item.get("nest_level", ""),
            "global_judge": item.get("global_judge", False),
            "corrected_full_sentence": corrected_full_sentence,
            "initial_check": initial_check,
        }
        return (full_sentence, [clause_tuple])

    def evaluate_semantic_conflict(
        self, item: dict, stage1_tuple: tuple
    ) -> dict:
        """Phase 2: Perform dual-validity evaluation and logic alignment based on full context and physical facts."""
        full_sentence, clauses = stage1_tuple
        clause_data = clauses[0]

        system_prompt = "You are a rigorous commonsense error and semantic conflict evaluation expert. Strictly output JSON structure without any Markdown commentary or extra text."

        prompt = f"""Evaluate the semantic validity of the sentence based on the clause slices, extracted full context shell, retrieved evidence, and gold correction reference.
【Input Data】:
- Original Full Sentence: "{full_sentence}"
- Core Pure Assertion (target_claim): "{clause_data['pure_assertion']}"
- LLM Context Shell (full_context_shell): "{clause_data['full_context_shell']}"
- LLM Context Constraint Properties (context_nature): "{clause_data['context_nature']}"
- Gold Correction Reference (corrected_full_sentence): "{clause_data['corrected_full_sentence']}"
- Physical Fact Evidence: {clause_data['initial_check'].get('cs_evidence', 'None')}
- Context Reference Evidence: {clause_data['initial_check'].get('ctx_evidence', 'None')}

【Evaluation Requirements】:
1. **reality_validity**: Does the core assertion conform to physical/scientific commonsense in the [Objective Real World] (true/false)?
2. **context_validity**: Does the specific [Context Shell] tolerate this assertion (true/false)? Note: Educational, academic, news, and scientific context shells MUST NOT tolerate scientific falsehoods. Only fictional, fairy tale, or dream contexts tolerate factual counterfactuals.
3. **coarse_label**: Select EXACTLY one from the following three categories:
   - If reality_validity=true AND context_validity=true   -> "VALID_IN_BOTH"
   - If reality_validity=false AND context_validity=true  -> "INVALID_IN_REALITY_BUT_VALID_IN_CONTEXT"
   - If reality_validity=false AND context_validity=false -> "INVALID_IN_BOTH"
4. **focus_guidance**: Summarize in one sentence what element in the assertion is flawed and needs to be replaced or revised based on the gold correction reference.

Strictly return JSON format:
{{
  "pure_assertion": "{clause_data['pure_assertion']}",
  "reality_validity": false,
  "context_validity": false,
  "coarse_label": "INVALID_IN_BOTH",
  "analysis": {{
    "reality_analysis": "Objective fact analysis...",
    "context_tolerance_analysis": "Context tolerance analysis..."
  }},
  "focus_guidance": "Revision focus guidance..."
}}
"""
        eval_json = self._call_ollama_json(system_prompt, prompt)
        
        if not eval_json:
            print("❌ DeepSeek-R1 output empty/invalid JSON, skipping sample.")
            return None

        return {
            "id": item.get("id", hash(full_sentence)),
            "full_sentence": full_sentence,
            "gold_label": item.get("global_judge", False),
            "corrected_full_sentence": item.get("correction", item.get("corrected_full_sentence", full_sentence)),
            "stage1_tuple": stage1_tuple,
            "conflict_evaluation": eval_json,
        }


def process_dataset(input_file: str = DATASET_PATH, max_samples: int = None):
    output_filename = os.path.basename(input_file).replace(
        ".jsonl", "_processed_stage1_2.jsonl"
    )
    output_path = os.path.join(os.path.dirname(input_file), output_filename)
    
    if not os.path.exists(input_file):
        print(f"❌ Cannot find input dataset: {input_file}")
        return

    # 1. Check breakpoint resume progress
    processed_sentences = set()
    if os.path.exists(output_path):
        with open(output_path, "r", encoding="utf-8") as f:
            for line in f:
                if line.strip():
                    data = json.loads(line)
                    processed_sentences.add(data.get("full_sentence"))
        print(f"🔄 Detected existing results. Skipping {len(processed_sentences)} completed samples.")

    # 2. Load unprocessed raw samples
    raw_samples = []
    with open(input_file, "r", encoding="utf-8") as f:
        for line in f:
            if line.strip():
                item = json.loads(line)
                if item.get("full_sentence") not in processed_sentences:
                    raw_samples.append(item)

    if max_samples:
        raw_samples = raw_samples[:max_samples]

    print(f"📊 Dataset: {os.path.basename(input_file)} | Remaining samples to process: {len(raw_samples)}\n")

    if not raw_samples:
        print("✅ All samples have been processed!")
        return

    processor = SCGProcessor(model_name=OLLAMA_MODEL)
    success_count = 0

    with open(output_path, "a", encoding="utf-8") as out_f:
        for item in tqdm(raw_samples, desc="Processing REAP Stage 1&2 (Ollama DeepSeek-R1-7B)"):
            try:
                stage1_tuple = processor.parse_dataset_item(item)
                result = processor.evaluate_semantic_conflict(item, stage1_tuple)
                if result:
                    out_f.write(json.dumps(result, ensure_ascii=False) + "\n")
                    out_f.flush()
                    success_count += 1
            except Exception as e:
                print(f"\n⚠️ Processing failed for sample: {item.get('full_sentence', '')[:15]}... Error: {e}")
                continue

    print(f"\n🎉 Batch execution complete! Successfully processed {success_count} samples.")
    print(f"💾 Phase 1 & 2 outputs saved to: {output_path}")


if __name__ == "__main__":
    process_dataset(input_file=DATASET_PATH, max_samples=10)