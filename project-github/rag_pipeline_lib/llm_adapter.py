# 💡 Ollama local model configuration for DeepSeek-R1-Distill-Qwen-7B
MODEL_NAME = getattr(config, "MODEL_NAME", "deepseek-r1:7b")


def clean_deepseek_reasoning_output(raw_content: str) -> str:
    """
    Cleans <think>...</think> reasoning tags generated by DeepSeek-R1
    and extracts pure JSON strings or code blocks.
    """
    if not raw_content:
        return "{}"
    
    # 1. Remove <think>...</think> tags and internal thinking steps
    cleaned = re.sub(r'<think>.*?</think>', '', raw_content, flags=re.DOTALL).strip()
    
    # 2. Extract content inside ```json ... ``` code blocks
    json_block = re.search(r'```json\s*(.*?)\s*```', cleaned, re.DOTALL)
    if json_block:
        return json_block.group(1).strip()
    
    # 3. Fallback: extract the outermost { ... } JSON object
    json_obj = re.search(r'\{.*\}', cleaned, re.DOTALL)
    if json_obj:
        return json_obj.group(0).strip()
    
    return cleaned


def traceable_llm_call(func):
    """Decorator to trace LLM calls across the REAP reasoning pipeline."""
    @wraps(func)
    def wrapper(*args, **kwargs):
        tracer = tracer_context.get()
        result = func(*args, **kwargs)
        if tracer:
            input_args = {key: value for key, value in kwargs.items()}
            arg_names = func.__code__.co_varnames[:func.__code__.co_argcount]
            for i, arg in enumerate(args):
                if i < len(arg_names):
                    input_args[arg_names[i]] = arg
            tracer.record_llm_call(
                adapter_function_name=func.__name__,
                inputs=input_args,
                output=result
            )
        return result
    return wrapper


def _call_ollama_chat(system_prompt: str, user_prompt: str, temperature: float = 0.1) -> str:
    """
    Local API call wrapper optimized for DeepSeek-R1-7B via Ollama.
    Enforces 8GB VRAM limits and JSON formatting.
    """
    try:
        # VRAM protection settings
        options = {
            "temperature": temperature,
            "num_ctx": 4096,     # Limit context window to save GPU memory
            "num_predict": 1024, # Limit response length
            "top_p": 0.95
        }

        response = ollama.chat(
            model=MODEL_NAME,
            messages=[
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_prompt}
            ],
            format="json",  # Force Ollama to generate structured JSON
            options=options
        )
        
        raw_content = response['message']['content']
        cleaned_json_str = clean_deepseek_reasoning_output(raw_content)
        return cleaned_json_str

    except Exception as e:
        print(f"⚠️ Ollama Local API Call Error: {e}")
        return "{}"


@traceable_llm_call
def decompose_tree(
    s0_input: Union[Dict[str, Any], str], 
    context_shell: str = "", 
    pure_assertion: str = ""
) -> str:
    """
    Tier 1: Reasoning Tree Decomposition.
    Supports full s0_dict objects (including Y_orig and groups list),
    as well as scalar fallback strings.
    """
    system_prompt = prompts.DECOMPOSER_SYSTEM_PROMPT
    
    if isinstance(s0_input, dict):
        s0_dict = s0_input
        y_orig = s0_dict.get("Y_orig", "")
        groups = s0_dict.get("groups", [])
        
        groups_detail = ""
        for g in groups:
            groups_detail += f"- Group ID: {g.get('group_id', 'group_0')}\n"
            groups_detail += f"  * Context Shell (C): {g.get('context_shell', '')}\n"
            groups_detail += f"  * Context Nature: {g.get('context_nature', '')}\n"
            groups_detail += f"  * Pure Assertion (A): {g.get('pure_assertion', '')}\n"
            groups_detail += f"  * Initial Intuition (I_0): {g.get('intuition_I0', {})}\n\n"
            
        user_prompt = prompts.DECOMPOSER_USER_PROMPT.format(
            Y_orig=y_orig,
            groups_detail=groups_detail
        )
    else:
        # Backward compatibility for scalar string arguments
        groups_detail = (
            f"- Group ID: group_0\n"
            f"  * Context Shell (C): {context_shell}\n"
            f"  * Pure Assertion (A): {pure_assertion}\n"
        )
        user_prompt = prompts.DECOMPOSER_USER_PROMPT.format(
            Y_orig=str(s0_input),
            groups_detail=groups_detail
        )
    return _call_ollama_chat(system_prompt, user_prompt, temperature=0.1)


@traceable_llm_call
def extract_facts_and_vector(
    query: str, 
    active_requirement: str, 
    known_facts: str, 
    retrieved_documents: str
) -> str:
    """Tier 2: Fact Extraction & Efficacy Vector Computation."""
    system_prompt = prompts.SYSTEM_PROMPT_FACT_EXTRACTION
    user_prompt = prompts.USER_PROMPT_FACT_EXTRACTION.format(
        query=query,
        active_requirement=active_requirement,
        known_facts=known_facts,
        retrieved_documents=retrieved_documents
    )
    return _call_ollama_chat(system_prompt, user_prompt, temperature=0.0)


@traceable_llm_call
def update_plan(query: str, completed_node_results: str, pending_requirements: str) -> str:
    """Tier 3: Dynamic Tree Node Scheduling."""
    system_prompt = prompts.SYSTEM_PROMPT_PLAN_UPDATER
    user_prompt = prompts.USER_PROMPT_PLAN_UPDATER.format(
        query=query,
        completed_node_results=completed_node_results,
        pending_requirements=pending_requirements
    )
    return _call_ollama_chat(system_prompt, user_prompt, temperature=0.1)


@traceable_llm_call
def evaluate_answer(question: str, golden_answer: str, predicted_answer: str) -> str:
    """Evaluates prediction truth value alignment against Golden labels."""
    system_prompt = "You are a logical evaluation officer. Assess whether the model's predicted truth value aligns with the standard ground truth."
    user_prompt = f"""Original Assertion: {question}
Standard Ground Truth: {golden_answer}
Predicted Decision: {predicted_answer}

Judge whether they are logically aligned and return JSON:
{{
  "is_correct": true,
  "explanation": "Brief reasoning..."
}}"""
    return _call_ollama_chat(system_prompt, user_prompt, temperature=0.0)